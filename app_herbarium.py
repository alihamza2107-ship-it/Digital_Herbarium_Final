def check_login(u, p):

    ok_u = hmac.compare_digest(
        u.strip().lower().encode(),
        APP_USER.lower().encode()
    )

    ok_p = hmac.compare_digest(
        p.strip().encode(),
        APP_PASS.encode()
    )

    return ok_u and ok_p


