def predict(img, model):

    h, w = model.input_shape[1:3]

    arr = np.asarray(
        img.convert("RGB"),
        dtype="float32"
    )[None]

    arr = tf.image.resize(
        arr,
        (h, w)
    ).numpy()

    return model.predict(
        arr,
        verbose=0
    )[0]


